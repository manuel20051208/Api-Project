"""Crea un .drawio.svg EDITABLE (se ve como imagen en GitHub/README y se abre en draw.io) a partir del XML.

Usa ver_drawio.py --svg para que el dibujo sea el del visor oficial, y mete el XML en el atributo `content`,
igual que la exportacion de draw.io. Fondo blanco fijo (no se oscurece en modo oscuro).

Uso: python exportar_drawio_svg.py diagrama.xml salida.drawio.svg
"""
import html
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

xml_path, salida = sys.argv[1], sys.argv[2]
crudo = os.path.join(tempfile.mkdtemp(), "crudo.svg")
subprocess.run([sys.executable, os.path.join(os.path.dirname(os.path.abspath(__file__)), "ver_drawio.py"),
                xml_path, crudo, "--svg"], check=True)
svg = open(crudo, encoding="utf-8").read()
w, h = [int(x) for x in re.search(r"min-width: (\d+)px; min-height: (\d+)px", svg).groups()]
W, H = w + 40, h + 40
modelo = open(xml_path, encoding="utf-8").read()
if modelo.startswith("<?xml"):
    modelo = modelo.split("?>", 1)[1].strip()
cab = re.match(r"<svg[^>]*>", svg).group(0)
raiz = (f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" version="1.1" '
        f'width="{W}px" height="{H}px" viewBox="-20 -20 {W} {H}" style="background: #ffffff; background-color: #ffffff;" '
        f'content="{html.escape(modelo, quote=True)}"><rect x="-20" y="-20" width="{W}" height="{H}" fill="#ffffff"/>')
cuerpo = raiz + svg[len(cab):]
ET.fromstring(cuerpo.encode("utf-8"))
with open(salida, "w", encoding="utf-8") as f:
    f.write('<?xml version="1.0" encoding="UTF-8"?>\n<!-- Do not edit this file with editors other than draw.io -->\n'
            '<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">\n'
            + cuerpo)
print(f"{salida} ({W} x {H})")
